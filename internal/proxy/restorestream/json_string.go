package restorestream

// commonJSONEscape 解码占用一个字节的 JSON 转义。Unicode 转义由原解码器处理。
func commonJSONEscape(c byte) (byte, bool) {
	switch c {
	case '"', '\\', '/':
		return c, true
	case 'b':
		return '\b', true
	case 'f':
		return '\f', true
	case 'n':
		return '\n', true
	case 'r':
		return '\r', true
	case 't':
		return '\t', true
	}
	return 0, false
}
